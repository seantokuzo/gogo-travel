#!/usr/bin/env node
/**
 * T-S3.1 (testing-overhaul spec §3.5, R-test-5; ADR-006 "Env strategy") —
 * generate a NEVER-COMMITTED `apps/server/.env.test` with throwaway auth key
 * material: the live-rig twin of the in-memory
 * `apps/server/src/test/env-builder.ts` builder, and the pattern the
 * 2026-08-29 QA rig proved by hand.
 *
 * Generated over committed (ADR-006 alternative #4, rejected commit): the
 * keys guard nothing, but Law #1's letter stays clean — no PEM blocks in git
 * history, no secret-scanner noise. `.env.test` is gitignored (`.env.*` +
 * an explicit entry).
 *
 * What it writes: NODE_ENV=development, the 8 all-or-nothing auth vars
 * (`buildAuthDepsFromEnv`, src/auth/wire.ts) with fresh P-256 PKCS#8 keys and
 * a 32-byte AES key, plus DATABASE_URL (see resolution order below). PEMs are
 * written `\n`-escaped in double quotes — the `.env.example`-documented form.
 * Node's `--env-file` does NOT expand `\n` (verified node 24.12); the wire
 * `pem()` normalizer handles it, and the boot-shape suite pins that arm.
 *
 * DATABASE_URL resolution: `--database-url <url>` flag → existing `.env.test`
 * value (preserved across --force regens) → `DATABASE_URL` in the calling
 * env → a commented placeholder (authed boot then throws until you set one —
 * all-or-nothing requires it).
 *
 *   node scripts/gen-test-env.mjs             # create (refuses to overwrite)
 *   node scripts/gen-test-env.mjs --force     # regen keys, keep DATABASE_URL
 *   pnpm --filter @gogo/server dev:testenv    # boot the dev server on it
 *
 * Law #1 posture: this script logs variable NAMES only, never values.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const envTestPath = join(repoRoot, "apps", "server", ".env.test");

const args = process.argv.slice(2);
const force = args.includes("--force");
const dbUrlFlagIndex = args.indexOf("--database-url");
const dbUrlFromFlag = dbUrlFlagIndex >= 0 ? args[dbUrlFlagIndex + 1] : undefined;
if (dbUrlFlagIndex >= 0 && !dbUrlFromFlag) {
  console.error("--database-url requires a value");
  process.exit(1);
}

if (existsSync(envTestPath) && !force) {
  console.error(
    "apps/server/.env.test already exists — pass --force to regenerate " +
      "(keys are replaced; an existing DATABASE_URL is preserved)",
  );
  process.exit(1);
}

/** DATABASE_URL from an existing .env.test (values never logged). */
function existingDatabaseUrl() {
  if (!existsSync(envTestPath)) return undefined;
  const match = readFileSync(envTestPath, "utf8").match(/^DATABASE_URL=(.+)$/m);
  return match ? match[1] : undefined;
}

/** Fresh throwaway P-256 private key as a `\n`-escaped PKCS#8 PEM line. */
function throwawayPkcs8Escaped() {
  const { privateKey } = generateKeyPairSync("ec", { namedCurve: "P-256" });
  const pem = privateKey.export({ type: "pkcs8", format: "pem" }).toString();
  return pem.replaceAll("\n", "\\n");
}

const databaseUrl = dbUrlFromFlag ?? existingDatabaseUrl() ?? process.env.DATABASE_URL;

const lines = [
  "# GENERATED by scripts/gen-test-env.mjs — THROWAWAY keys for the local",
  "# test/dev rig. Gitignored; NEVER commit (Law #1). Regenerate any time:",
  "#   node scripts/gen-test-env.mjs --force",
  "",
  "NODE_ENV=development",
  "# PORT=3000",
  "",
  databaseUrl !== undefined
    ? `DATABASE_URL=${databaseUrl}`
    : "# Authed boot REQUIRES a database url (all-or-nothing gate) — set one:\n" +
      "# DATABASE_URL=postgresql://user:password@localhost:5432/gogo_dev",
  "",
  "# The 8 all-or-nothing auth vars (src/auth/wire.ts). PEMs are \\n-escaped;",
  "# node --env-file does NOT expand them — the server normalizes (wire pem()).",
  `AUTH_ES256_PRIVATE_KEY="${throwawayPkcs8Escaped()}"`,
  "AUTH_ES256_KID=testenv-kid-1",
  "APPLE_CLIENT_ID=com.gogo.travel.testenv",
  "GOOGLE_CLIENT_IDS=testenv-ios.apps.example,testenv-web.apps.example",
  "APPLE_TEAM_ID=TESTENVTEAM",
  "APPLE_KEY_ID=TESTENVKEY1",
  `APPLE_PRIVATE_KEY="${throwawayPkcs8Escaped()}"`,
  `APPLE_CREDENTIALS_KEY=${randomBytes(32).toString("base64")}`,
  "",
];

writeFileSync(envTestPath, lines.join("\n"), { mode: 0o600 });

console.warn(`wrote apps/server/.env.test (mode 600) with throwaway values for:`);
console.warn("  NODE_ENV, AUTH_ES256_PRIVATE_KEY, AUTH_ES256_KID, APPLE_CLIENT_ID,");
console.warn("  GOOGLE_CLIENT_IDS, APPLE_TEAM_ID, APPLE_KEY_ID, APPLE_PRIVATE_KEY,");
console.warn("  APPLE_CREDENTIALS_KEY" + (databaseUrl !== undefined ? ", DATABASE_URL" : ""));
if (databaseUrl === undefined) {
  console.warn(
    "no DATABASE_URL resolved — wrote a commented placeholder; authed boot " +
      "will refuse until you set one (--database-url <url>, or edit the file)",
  );
}
console.warn("boot it:  pnpm --filter @gogo/server dev:testenv");
